/// <summary>One fixed composite symbol input and its complete module rows.</summary>
internal sealed class Gs1CompositeVector
{
    internal Gs1CompositeVector(
        string name,
        string linearComponent,
        string primaryData,
        string secondaryData,
        string mode,
        int width,
        IReadOnlyList<string> rows)
    {
        Name = name ?? throw new ArgumentNullException(nameof(name));
        LinearComponent = linearComponent ?? throw new ArgumentNullException(nameof(linearComponent));
        PrimaryData = primaryData ?? throw new ArgumentNullException(nameof(primaryData));
        SecondaryData = secondaryData ?? throw new ArgumentNullException(nameof(secondaryData));
        Mode = mode ?? throw new ArgumentNullException(nameof(mode));
        Width = width;
        Rows = rows ?? throw new ArgumentNullException(nameof(rows));
    }

    internal string Name { get; }
    internal string LinearComponent { get; }
    internal string PrimaryData { get; }
    internal string SecondaryData { get; }
    internal string Mode { get; }
    internal int Width { get; }
    internal IReadOnlyList<string> Rows { get; }
    internal int Height => Rows.Count;

    internal void Validate()
    {
        if (Width <= 0)
            throw new InvalidOperationException("Composite vector width must be positive.");

        if (Rows.Count == 0)
            throw new InvalidOperationException("Composite vector must contain at least one row.");

        for (var rowIndex = 0; rowIndex < Rows.Count; rowIndex++)
        {
            var row = Rows[rowIndex];
            if (row == null || row.Length != Width)
            {
                throw new InvalidOperationException(
                    $"Composite vector row {rowIndex} has width {row?.Length ?? 0}; expected {Width}.");
            }

            for (var columnIndex = 0; columnIndex < row.Length; columnIndex++)
            {
                if (row[columnIndex] != '0' && row[columnIndex] != '1')
                {
                    throw new InvalidOperationException(
                        $"Composite vector row {rowIndex} column {columnIndex} is not a module bit.");
                }
            }
        }
    }
}
