namespace Bing.EasyPrint.Elements
{
    /// <summary>
    /// 指定文字在元素可用区域内的水平对齐方式。
    /// </summary>
    public enum BpTextAlignment
    {
        /// <summary>
        /// 将文字靠可用区域左侧排列。
        /// </summary>
        Left = 0,
        /// <summary>
        /// 将文字在可用区域内水平居中排列。
        /// </summary>
        Center = 1,
        /// <summary>
        /// 将文字靠可用区域右侧排列。
        /// </summary>
        Right = 2
    }
}
